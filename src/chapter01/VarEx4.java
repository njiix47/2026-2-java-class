package chapter01;

public class VarEx4 {
    public static void main(String[] args) {
        byte a = 10;
        short b = 200;
        //byte c = 150; //byte 형으로 표현 가능한 범위를 넘음
        int d = 300;
        long e = 5000000000L; //long 자료형 값 뒤 'L'을 사용하지 않음
        float f = 5.7F; // float 자료형 값 뒤 'F'를 사용하지 않음
        double g = 5.7;
        boolean h = true;
        char i = 'A';
    }
}
